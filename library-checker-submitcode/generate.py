"""Build standalone submissions from the template, libraries, and problem code."""

import argparse
from pathlib import Path
import re
import sys


BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
SOURCES = BASE / "src"
INCLUDE = re.compile(r"^# include: (.+)$", re.MULTILINE)


def render(source):
    def include(match):
        path = ROOT / match.group(1).strip()
        return "\n".join(
            [
                f"# BEGIN LIBRARY: {path.relative_to(ROOT).as_posix()}",
                path.read_text(encoding="utf-8").rstrip(),
                "# END LIBRARY",
            ]
        )

    template = (BASE / "template.py").read_text(encoding="utf-8").rstrip()
    body = INCLUDE.sub(include, source.read_text(encoding="utf-8")).rstrip()
    origin = source.relative_to(BASE).as_posix()
    result = (
        f"{template}\n# Generated by generate.py; edit {origin} instead.\n\n{body}\n"
    )
    compile(result, str(source), "exec")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report outdated submissions without writing",
    )
    args = parser.parse_args()
    outdated = False
    for source in sorted(SOURCES.rglob("*.py")):
        output = BASE / source.relative_to(SOURCES)
        result = render(source)
        if output.exists() and output.read_text(encoding="utf-8") == result:
            continue
        if args.check:
            print(f"outdated: {output.relative_to(ROOT)}", file=sys.stderr)
            outdated = True
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(result, encoding="utf-8")
            print(f"generated: {output.relative_to(ROOT)}")
    if outdated:
        print("Run: python3 library-checker-submitcode/generate.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
