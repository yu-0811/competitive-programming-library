"""Build standalone submissions from the template, libraries, and problem code."""

import argparse
import ast
import re
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
SOURCES = BASE / "src"
INCLUDE = re.compile(r"^# include: (.+)$", re.MULTILINE)
PROBLEM = re.compile(
    r"^# problem: (https://judge\.yosupo\.jp/problem/\w+)$", re.MULTILINE
)


def render(source):
    included = set()

    def expand(path):
        path = path.resolve()
        if path in included:
            return ""
        included.add(path)
        content = path.read_text(encoding="utf-8").rstrip()
        lines = content.splitlines(keepends=True)
        chunks = []
        cursor = 0
        for node in ast.parse(content).body:
            if not isinstance(node, ast.ImportFrom) or not node.module:
                continue
            if not node.module.startswith("algorithm_library.python."):
                continue
            parts = node.module.split(".")
            dependency = ROOT.joinpath(*parts).with_suffix(".py")
            if node.level or any(alias.asname or alias.name == "*" for alias in node.names):
                raise ValueError(f"Unsupported library import in {path}: {ast.unparse(node)}")
            chunks.extend(lines[cursor : node.lineno - 1])
            chunks.append(expand(dependency) + "\n")
            cursor = node.end_lineno
        chunks.extend(lines[cursor:])
        return "\n".join(
            [
                f"# BEGIN LIBRARY: {path.relative_to(ROOT).as_posix()}",
                "".join(chunks).rstrip(),
                "# END LIBRARY",
            ]
        )

    def include(match):
        path = ROOT / match.group(1).strip()
        return expand(path)

    template = (BASE / "template.py").read_text(encoding="utf-8").rstrip()
    body = INCLUDE.sub(include, source.read_text(encoding="utf-8")).rstrip()
    origin = source.relative_to(BASE).as_posix()
    result = (
        f"{template}\n# Generated by generate.py; edit {origin} instead.\n\n{body}\n"
    )
    compile(result, str(source), "exec")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report outdated submissions without writing",
    )
    args = parser.parse_args()
    outdated = False
    for source in sorted(SOURCES.rglob("*.py")):
        relative = source.relative_to(SOURCES)
        result = render(source)
        problems = PROBLEM.findall(source.read_text(encoding="utf-8"))
        if len(problems) != 1:
            print(
                f"Expected one # problem: URL in {source.relative_to(ROOT)}",
                file=sys.stderr,
            )
            return 1
        output = BASE / relative.with_suffix(".test.py")
        content = f"# verification-helper: PROBLEM {problems[0]}\n{result}"
        if output.exists() and output.read_text(encoding="utf-8") == content:
            continue
        if args.check:
            print(f"outdated: {output.relative_to(ROOT)}", file=sys.stderr)
            outdated = True
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(content, encoding="utf-8")
            print(f"generated: {output.relative_to(ROOT)}")
    if outdated:
        print("Run: python3 library-checker-submitcode/generate.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
