# 小さい整数用の試し割り O(√n)
def is_prime(n):
    if n < 2 or n % 2 == 0:
        return n == 2
    for d in range(3, isqrt(n) + 1, 2):
        if n % d == 0:
            return False
    return True


# 64 ビット整数用の決定的 Miller–Rabin。単独で写せる。
# 判定 1 回につき O(k log n) 回の剰余乗算（k は基数の個数、最大 7）。
def is_prime64(n):
    assert n < 1 << 64
    if n < 2:
        return False
    for p in (2, 3, 5, 7):
        if n % p == 0:
            return n == p
    d = n - 1
    r = (d & -d).bit_length() - 1
    d >>= r  # n - 1 = d * 2**r、d は奇数
    bases = (2, 7, 61) if n < 1 << 32 else (
        2, 325, 9375, 28178, 450775, 9780504, 1795265022
    )
    for a in bases:
        x = pow(a, d, n)
        if x == 1 or a % n == 0:
            continue
        for _ in range(r):
            if x == n - 1:
                break
            x = x * x % n
        else:
            return False
    return True


# 最小素因数表の前計算。時間 O(N log log N)、空間 O(N)。
# 参考 https://atcoder.jp/contests/abc177/editorial/82
def init_factorization(N: int) -> list[int]:
    # N 以下の整数に対して最小の素因数を求める
    # D[i] = i の最小の素因数
    D = list(range(N + 1))
    for i in range(2, isqrt(N) + 1):
        if D[i] == i:
            for j in range(i * i, N + 1, i):
                if D[j] == j:
                    D[j] = i
    return D


D = []  # 使用前に D = init_factorization(N) で初期化する


# 1 <= x <= N を素因数分解する。1 回あたり最悪 O(log x)。
# ループ回数は重複を含む素因数の個数。
def factorization(x: int) -> dict[int, int]:
    res = defaultdict(int)
    while x != 1:
        res[D[x]] += 1
        x //= D[x]
    return res


# エラトステネスの篩
# O (N log log N)
def eratosthenes(N: int):
    # 素数
    isprime = bytearray(b"\1") * (N + 1)  # isprime[i]==True なら i は素数
    isprime[:2] = bytes(min(2, N + 1))
    for p in range(2, isqrt(N) + 1):
        if isprime[p]:
            isprime[p * p::p] = bytes((N - p * p) // p + 1)
    return [p for p in range(2, N + 1) if isprime[p]], [bool(x) for x in isprime]


# M 以下の素数リストを返す
# O(M log log M)
def res_primeList(M):
    if M < 2:
        return []
    root = isqrt(M)
    small = res_primeList(root)[1:]  # √M 以下の奇素数
    width = max(1 << 18, root)
    limit = (M + 1) // 2
    res = [2]
    for lo in range(1, limit, width):
        n = min(width, limit - lo)
        flags = bytearray(b"\1") * n  # flags[i] は 2*(lo+i)+1 に対応
        for p in small:
            j = p * p // 2 - lo
            if j >= n:
                break
            if j < 0:
                j %= p
            flags[j::p] = bytes((n - 1 - j) // p + 1)
        res.extend([2 * (lo + i) + 1 for i in range(n) if flags[i]])
    return res
