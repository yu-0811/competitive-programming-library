class Comb:
    def __init__(self, k, mod):
        self.mod = mod
        f = self.fact_inv = [1] * (k + 1)
        for i in range(2, k + 1):
            f[i] = f[i - 1] * i % mod
        f[k] = pow(f[k], -1, mod)
        for i in range(k, 0, -1):
            f[i - 1] = f[i] * i % mod

    def nCk(self, n, k):  # min(k, n-k) <= 前計算の上限
        if not 0 <= k <= n:
            return 0
        k = min(k, n - k)
        mod = self.mod
        ans = self.fact_inv[k]
        n %= mod
        if n < k:
            return 0
        for i in range(k):
            ans = ans * (n - i) % mod
        return ans
