class SparseTable:
    def __init__(self, arr, op):
        """
        arr: 配列
        op: 演算 (結合則、冪等則を満たすこと)
        時間計算量: O(n log n) 構築, O(1) クエリ
        空間計算量: O(n log n)
        """
        self.op = op
        self.n = n = len(arr)
        mk = n.bit_length()
        # table[k][i] = i から長さ 2^k の区間に対する演算結果
        self.table = table = [arr[:]] if n else []

        for k in range(1, mk):
            half_len = 1 << (k - 1)
            prev = table[-1]
            table.append(
                [op(prev[i], prev[i + half_len]) for i in range(n - (1 << k) + 1)]
            )

    def query(self, l, r):
        """
        [l, r) の区間に対する演算結果を返す O(1)
        """
        assert 0 <= l < r <= self.n
        # 2^k <= r - l を満たす最大の k を求める
        k = (r - l).bit_length() - 1
        # [l, l + 2^k) と [r - 2^k, r) の区間に分割して計算
        return self.op(self.table[k][l], self.table[k][r - (1 << k)])


class fenwick_tree:
    n = 1
    data = [0 for i in range(n)]

    # N 要素の配列を 0 で初期化する
    def __init__(self, N):
        self.n = N
        self.data = [0 for i in range(N)]

    # p 番目の要素に x を加算する
    def add(self, p, x):
        assert 0 <= p < self.n, "0<=p<n,p={0},n={1}".format(p, self.n)
        p += 1
        while p <= self.n:
            self.data[p - 1] += x
            p += p & -p

    # [l, r) の和を返す
    def sum(self, l, r):
        assert 0 <= l and l <= r and r <= self.n, "0<=l<=r<=n,l={0},r={1},n={2}".format(
            l, r, self.n
        )
        return self.sum0(r) - self.sum0(l)

    # [0, r) の和を返す
    def sum0(self, r):
        s = 0
        data = self.data
        while r > 0:
            s += data[r - 1]
            r -= r & -r
        return s


class EulerTour:
    # N 頂点の木を初期化する
    def __init__(s, N):
        s.N = N
        s.G = [[] for _ in range(N + 1)]
        s._in = [-1] * (N + 1)  # 各頂点の訪問開始時刻
        s._out = [-1] * (N + 1)  # 各頂点の訪問終了時刻
        s.m = 0  # 辺数
        s.ws = []  # ツアー順の辺の重み
        s.es = []  # ツアー順の辺番号
        s.vs = []  # ツアー順の頂点番号
        s.depth = [-1]
        s.base = 1 << N.bit_length()
        s.mask = s.base - 1

    # 辺の重みの和を管理する Fenwick Tree を O(N) で構築する
    def _build_fentree(s):
        n = len(s.ws)
        s.fen = fenwick_tree(n)
        d = s.fen.data = s.ws[:]
        if d:
            d[0] = 0
        for i in range(1, n + 1):
            j = i + (i & -i)
            if j <= n:
                d[j - 1] += d[i - 1]

    # LCA 用の区間最小値を求める SparseTable を構築する
    def _build_lca(s):
        a = [d * s.base + abs(v) for d, v in zip(s.depth, s.vs)]
        s.lca_table = SparseTable(a, min)

    # 無向辺 u-v を重さ w で追加する
    def add_edge(s, u, v, w):
        s.m += 1
        s.G[u].append((v, w, s.m))
        s.G[v].append((u, w, s.m))

    # root を根としてオイラーツアーとクエリ用のデータ構造を構築する
    def build(s, root):
        s.root = root
        st = [(root, 0, 0)]
        while st:
            v, w, i = st.pop()
            t = len(s.es)
            if v >= 0:
                s._in[v] = s._out[v] = t
                s.vs.append(v)
                s.depth.append(s.depth[-1] + 1)
                for e in s.G[v]:
                    if s._in[e[0]] < 0:
                        st.append((~v, -e[1], -e[2]))
                        st.append(e)
            else:
                v = ~v
                s._out[v] = t
                s.vs.append(-v)
                s.depth.append(s.depth[-1] - 1)
            s.es.append(i)
            s.ws.append(w)
        s.depth.pop(0)
        s._build_fentree()
        s._build_lca()

    # 根から u へのパスのコストの和を返す
    def path_sum(s, u):
        return s.fen.sum0(s._in[u] + 1)

    # u と v の最小共通祖先を O(1) で返す
    def lca(s, u, v):
        l, r = s._in[u], s._in[v]
        if l > r:
            l, r = r, l
            u = v
        if r <= s._out[u]:
            return u
        return s.lca_table.query(l, r + 1) & s.mask

    # パス u-v のコストの和を返す
    def get_distance(s, u, v):
        a = s.lca(u, v)
        return s.path_sum(u) + s.path_sum(v) - 2 * s.path_sum(a)
