class ProductBIT:  # 1点乗算・1点代入・1点取得・区間積（整数、ゼロ可）
    def __init__(s, a):
        s.z = BIT([int(x == 0) for x in a])
        d = s.d = a
        n = s.n = len(d)
        for i in range(n):
            # 積を持つ配列では、ゼロを単位元の 1 として扱う。
            d[i] = d[i] or 1
            j = i | (i + 1)
            if j < n:
                d[j] = (d[j] or 1) * d[i]

    def add(s, p, x):  # a[p] *= x
        assert 0 <= p < s.n
        if x == 0:
            s.set(p, 0)
            return
        if s.z.get(p):
            return
        d = s.d
        while p < s.n:
            d[p] *= x
            p |= p + 1

    def set(s, p, x):
        z = s.z.get(p)
        a = 1 if z else s._prod0(p + 1) // s._prod0(p)
        s.z.add(p, int(x == 0) - z)
        d = s.d
        x = x or 1
        while p < s.n:
            d[p] = d[p] // a * x
            p |= p + 1

    def get(s, p):
        return s.prod(p, p + 1)

    def _prod0(s, r):
        res = 1
        while r:
            res *= s.d[r - 1]
            r &= r - 1
        return res

    def prod0(s, r):
        return s.prod(0, r)

    def prod(s, l, r):
        assert 0 <= l <= r <= s.n
        if s.z.prod(l, r):
            return 0
        return s._prod0(r) // s._prod0(l)
