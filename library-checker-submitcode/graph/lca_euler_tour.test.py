class RangeAddBIT: # 区間加算区間和
    def __init__(s, n):
        s.n = n
        s.bit = [[0] * s.n for _ in range(2)]

    # 初期配列 a から O(n) で構築する場合は __init__ をこちらに差し替える。
    # def __init__(s, a):
