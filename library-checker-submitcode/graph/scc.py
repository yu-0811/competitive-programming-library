class SCC:
    def __init__(self, N: int):
        self.N = N  # 頂点数
        self.edges = []  # 辺

    def addEdge(self, frm: int, to: int):
        assert 0 <= frm <= self.N
        assert 0 <= to <= self.N
        self.edges.append([frm, to])

    # 辺を CSR 形式にする(別にCSRじゃなくてもできるが高速化のため)
    def _csr(self, N: int, edges: list[list]):
        start = [0] * (N + 1)
        # dst := 辺を始点の昇順にソートした時の終点のリスト
        dst = [0] * len(edges)

        # start[i+1] := 頂点 i を始点とする辺の数 となるように構築
        for u, _ in edges:  # u を始点とする辺
            start[u + 1] += 1
        # start[i] := 始点の頂点番号が i 未満である辺の数 になるように累積和を取る
        # このとき、start[i] = dst で頂点 i が始点となる最小の index (0-index)
        for i in range(1, N + 1):
            start[i] += start[i - 1]

        # pos[i] := 始点を i とする辺の dst への挿入位置
        pos = start[:]
        for u, v in edges:
            dst[pos[u]] = v
            pos[u] += 1

        return start, dst

    # 強連結成分分解をする
    def _scc_ids(self):
        N = self.N
        start, dst = self._csr(N, self.edges)
        it = start[:-1]  # 各頂点で次に調べる辺の位置
        timer = 0  # 訪れた頂点数
        count = 0  # 見つかった強連結成分の数
        active = []  # 探索済みかつ所属成分が未確定の頂点
        lowlink = [0] * N
        order = [-1] * N  # 頂点の行きがけ順
        parent = [-1] * N
        comp = [0] * N

        for root in range(N):
            if order[root] != -1:
                continue
            stack = [root]
            lowlink[root] = order[root] = timer
            timer += 1
            active.append(root)
            while stack:
                v = stack[-1]
                i = it[v]
                if i < start[v + 1]:
                    it[v] = i + 1
                    to = dst[i]
                    if order[to] == -1:
                        parent[to] = v
                        lowlink[to] = order[to] = timer
                        timer += 1
                        active.append(to)
                        stack.append(to)
                    elif lowlink[v] > order[to]:
                        lowlink[v] = order[to]
                else:  # 帰りがけ
                    stack.pop()
                    if lowlink[v] == order[v]:
                        while True:
                            u = active.pop()
                            order[u] = N  # 確定した成分を lowlink の計算から除く
                            comp[u] = count
                            if u == v:
                                break
                        count += 1
                    pv = parent[v]
                    if pv != -1 and lowlink[pv] > lowlink[v]:
                        lowlink[pv] = lowlink[v]
        # 縮約後のグラフで comp をトポロジカルソート順にする
        for v in range(N):
            comp[v] = count - 1 - comp[v]

        return count, comp

    # groups[i] = グループID i に属する頂点の集合を 返す
    def build_scc(self) -> list[list[int]]:
        count, comp = self._scc_ids()
        groups = [[] for _ in range(count)]
        for v in range(self.N):
            groups[comp[v]].append(v)
        return groups

    # 強連結成分分解後のグラフを構築する(同一の強連結成分内の頂点は縮約)
    def build_dag(self) -> list[list[int]]:
        # comp[i] = 頂点 i が属する強連結成分の ID
        count, comp = self._scc_ids()
        # dag[i] = 強連結成分 i から出る辺の行き先の強連結成分の ID
        dag = [[] for _ in range(count)]
        for u, v in self.edges:
            if comp[u] != comp[v]:
                dag[comp[u]].append(comp[v])
        return dag
