class lazy_segtree:  # すべて 0-index
    def _push(s, k):
        lz = s.lz
        f = lz[k]
        # 初期状態・伝播済みのタグは何もしない
        if f is s.ide:
            return
        d, mp, comp = s.d, s.mp, s.comp
        c = 2 * k
        d[c] = mp(f, d[c])
        d[c + 1] = mp(f, d[c + 1])
        if c < s.z:
            lz[c] = comp(f, lz[c])
            lz[c + 1] = comp(f, lz[c + 1])
        lz[k] = s.ide

    def __init__(s, V, op, E, mp, comp, ID):
        s.n = len(V)
        s.log = (s.n - 1).bit_length()
        z = s.z = 1 << s.log
        d = s.d = [E] * (2 * z)
        s.lz = [ID] * z
        s.e = E
        s.op = op
        s.mp = mp
        s.comp = comp
        s.ide = ID
        d[z : z + s.n] = V
        for i in range(z - 1, 0, -1):
            d[i] = op(d[2 * i], d[2 * i + 1])

    # 一点更新
    def set(s, p, x):
        assert 0 <= p < s.n
        d, op, push = s.d, s.op, s._push
        p += s.z
        for i in range(s.log, 0, -1):
            push(p >> i)
        d[p] = x
        p >>= 1
        while p:
            d[p] = op(d[2 * p], d[2 * p + 1])
            p >>= 1

    # d[p] を取得する
    def get(s, p):
        assert 0 <= p < s.n
        push = s._push
        p += s.z
        for i in range(s.log, 0, -1):
            push(p >> i)
        return s.d[p]

    # 区間 [l,r) の演算結果を返す
    def prod(s, l, r):
        assert 0 <= l <= r <= s.n
        if l == r:
            return s.e
        d, op, push = s.d, s.op, s._push
        l += s.z
        r += s.z
        # 境界が揃わず、伝播・再計算が必要になる最初の段
        left = (l & -l).bit_length()
        right = (r & -r).bit_length()
        for i in range(s.log, 0, -1):
            if i >= left:
                push(l >> i)
            if i >= right:
                push(r >> i)
        sml = smr = s.e
        while l < r:
            if l & 1:
                sml = op(sml, d[l])
                l += 1
            if r & 1:
                smr = op(d[r - 1], smr)
            l >>= 1
            r >>= 1
        return op(sml, smr)

    # 全区間の演算結果を返す
    def all_prod(s):
        return s.d[1]

    # 一点に対して操作する
    def apply_point(s, p, f):
        assert 0 <= p < s.n
        d, op, push = s.d, s.op, s._push
        p += s.z
        for i in range(s.log, 0, -1):
            push(p >> i)
        d[p] = s.mp(f, d[p])
        p >>= 1
        while p:
            d[p] = op(d[2 * p], d[2 * p + 1])
            p >>= 1

    # 区間操作
    # f は mp に与える引数の f
    def apply(s, l, r, f):
        assert 0 <= l <= r <= s.n
        if l == r:
            return
        d, lz = s.d, s.lz
        op, mp, comp = s.op, s.mp, s.comp
        push, z = s._push, s.z
        l += z
        r += z
        # 境界が揃わず、伝播・再計算が必要になる最初の段
        left = (l & -l).bit_length()
        right = (r & -r).bit_length()
        for i in range(s.log, 0, -1):
            if i >= left:
                push(l >> i)
            if i >= right:
                push(r >> i)
        l2, r2 = l, r
        while l < r:
            if l & 1:
                d[l] = mp(f, d[l])
                if l < z:
                    lz[l] = comp(f, lz[l])
                l += 1
            if r & 1:
                r -= 1
                d[r] = mp(f, d[r])
                if r < z:
                    lz[r] = comp(f, lz[r])
            l >>= 1
            r >>= 1
        for i in range(1, s.log + 1):
            if i >= left:
                k = l2 >> i
                d[k] = op(d[2 * k], d[2 * k + 1])
            if i >= right:
                k = r2 >> i
                d[k] = op(d[2 * k], d[2 * k + 1])

    # check(operate(data[l],data[l+1],...,data[r-1])) = True
    # を満たす最大の r を返す
    def max_right(s, l, check):
        assert 0 <= l <= s.n
        assert check(s.e)
        if l == s.n:
            return s.n
        d, op, push = s.d, s.op, s._push
        z = s.z
        l += z
        for i in range(s.log, 0, -1):
            push(l >> i)
        sm = s.e
        while True:
            while l % 2 == 0:
                l >>= 1
            nxt = op(sm, d[l])
            if not check(nxt):
                while l < z:
                    push(l)
                    l *= 2
                    nxt = op(sm, d[l])
                    if check(nxt):
                        sm = nxt
                        l += 1
                return l - z
            sm = nxt
            l += 1
            if (l & -l) == l:
                return s.n

    # check(operate(data[l],data[l+1],...,data[r-1])) = True
    # を満たす最小の l を返す
    def min_left(s, r, check):
        assert 0 <= r <= s.n
        assert check(s.e)
        if r == 0:
            return 0
        d, op, push = s.d, s.op, s._push
        z = s.z
        r += z
        for i in range(s.log, 0, -1):
            push((r - 1) >> i)
        sm = s.e
        while True:
            r -= 1
            while r > 1 and (r % 2):
                r >>= 1
            nxt = op(d[r], sm)
            if not check(nxt):
                while r < z:
                    push(r)
                    r = 2 * r + 1
                    nxt = op(d[r], sm)
                    if check(nxt):
                        sm = nxt
                        r -= 1
                return r + 1 - z
            sm = nxt
            if (r & -r) == r:
                return 0

    # print(seg) で遅延を反映した要素を表示（O(N log N)）
    def __str__(s):
        return str([s.get(i) for i in range(s.n)])


