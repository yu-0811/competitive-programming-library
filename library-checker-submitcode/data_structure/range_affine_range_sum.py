def combine(left, right):
    return (left[0] + right[0]) % mod, left[1] + right[1]


def mapping(f, value):
    a, b = f
    total, length = value
    return (a * total + b * length) % mod, length


def composition(f, g):
    a, b = f
    c, d = g
    return a * c % mod, (a * d + b) % mod


