    def rangeadd(s, l, r, x):  # [l,r)にxを加算
        b0, b1 = s.bit
        n = s.n
        c = -x * l
        while l < n:
            b0[l] += c
            b1[l] += x
            l |= l + 1
        c = x * r
        while r < n:
            b0[r] += c
            b1[r] -= x
            r |= r + 1

    def _sum(s, i): # 区間 [0, i) の和
        b0, b1 = s.bit
        s0 = s1 = 0
        idx = i - 1
        while idx >= 0:
            s0 += b0[idx]
            s1 += b1[idx]
            idx = (idx & (idx + 1)) - 1
        return s0 + s1 * i

    def sum(s, l, r): # 区間 [l, r) の和
        return s._sum(r) - s._sum(l)

    # a[0] + ... + a[x] >= w となる最小の x を O(log n) で求める
    # 各要素は非負であること。w <= 0 なら 0、見つからなければ n
    def lower_bound(s, w):
        if w <= 0:
            return 0

        b0, b1 = s.bit
        n = s.n
        x = -1
        s0 = s1 = 0
        step = 1 << n.bit_length()
        while step:
            nxt = x + step
            if nxt < n:
                t0 = s0 + b0[nxt]
                t1 = s1 + b1[nxt]
                if t0 + t1 * (nxt + 1) < w:
                    x, s0, s1 = nxt, t0, t1
            step >>= 1
        return x + 1


