class MinBIT:  # 1点代入（減少のみ）・1点取得・区間最小値
    op = min
    cmp = lt
    e = 10**18  # 値域は -10**18 以上 10**18 以下。

    def __init__(s, a):
        s.a = a
        n = s.n = len(a)
        op = s.op
        # 内部は 1-indexed。b0[i] は i が右端、b1[i] は i が左端。
        b0 = s.b0 = [s.e] + a
        b1 = s.b1 = b0[:]
        for i in range(1, n + 1):
            j = i + (i & -i)
            if j <= n:
                b0[j] = op(b0[j], b0[i])
        for i in range(n, 0, -1):
            j = i & (i - 1)
            if j:
                b1[j] = op(b1[j], b1[i])

    def set(s, p, x):
        n = s.n
        assert 0 <= p < n
        a, b0, b1, cmp = s.a, s.b0, s.b1, s.cmp
        y = a[p]
        assert cmp(x, y) or x == y
        a[p] = x
        # 親は子の区間を含むので、極値が変わらない時点で止める。
        i = p + 1
        while i <= n and cmp(x, b0[i]):
            b0[i] = x
            i += i & -i
        i = p + 1
        while i and cmp(x, b1[i]):
            b1[i] = x
            i &= i - 1

    def get(s, p):
        assert 0 <= p < s.n
        return s.a[p]

    def prod0(s, r):
        return s.prod(0, r)

    def prod(s, l, r):
        assert 0 <= l <= r <= s.n
        res = s.e
        if l == r:
            return res
        b0, b1, op = s.b0, s.b1, s.op
        l += 1
        while l < r:
            j = l + (l & -l)
            if j > r:
                break
            res = op(res, b1[l])
            l = j
        while l < r:
            res = op(res, b0[r])
            r &= r - 1
        return op(res, s.a[l - 1])


