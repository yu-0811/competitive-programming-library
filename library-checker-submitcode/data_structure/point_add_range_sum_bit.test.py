    def __init__(s, a):
        d = s.d = a
        n = s.n = len(d)
        for i in range(n):
            j = i | (i + 1)
            if j < n:
                d[j] += d[i]

    def add(s, p, x):
        assert 0 <= p < s.n
        d = s.d
