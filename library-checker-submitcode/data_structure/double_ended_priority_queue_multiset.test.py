import math
from bisect import bisect_left, bisect_right

class SortedMultiset:
    br = 16
    sr = 24
    
    def __init__(s, a=[]):
        "ソート済みなら O(N)、それ以外は O(N log N)"
        a = sorted(a)
        n = s.size = len(a)
        k = math.ceil(math.sqrt(n / s.br))
        s.a = [a[n * i // k : n * (i + 1) // k] for i in range(k)]

    def __iter__(s):
        for a in s.a: yield from a
    
    def _position(s, x):
        "x を挿入するバケット、その添字、バケット内の挿入位置を返す。s は空でないこと。"
        for i, a in enumerate(s.a):
            if x <= a[-1]: break
        return (a, i, bisect_left(a, x))

    def __contains__(s, x):
        if s.size == 0: return False
        a, _, i = s._position(x)
        return i != len(a) and a[i] == x

    def count(s, x):
        "x の出現回数を返す。"
        return s.index_right(x) - s.index(x)

    def add(s, x):
        "x を 1 個追加する。 / O(√N)"
        if s.size == 0:
            s.a = [[x]]
            s.size = 1
            return
        a, b, i = s._position(x)
        a.insert(i, x)
        s.size += 1
        if len(a) > len(s.a) * s.sr:
            mid = len(a) >> 1
            s.a[b:b+1] = [a[:mid], a[mid:]]
    
    def _pop(s, a, b, i):
        ans = a.pop(i)
        s.size -= 1
        if not a: del s.a[b]
        return ans

    def discard(s, x):
        "x を 1 個削除し、削除できたら True を返す。 / O(√N)"
        if s.size == 0: return False
        a, b, i = s._position(x)
        if i == len(a) or a[i] != x: return False
        s._pop(a, b, i)
        return True

    # lt・gt・index_right は整数用。小数では le・ge・index を複製し、以下のコメントに従って変更する。
    def lt(s, x):
        "x 未満の最大の要素を返す。存在しなければ None を返す。"
        return s.le(x - 1)

    def le(s, x):
        "x 以下の最大の要素を返す。存在しなければ None を返す。"
        for a in reversed(s.a):
            if a[0] <= x:  # lt なら <
                return a[bisect_right(a, x) - 1]  # lt なら bisect_left

    def gt(s, x):
        "x より大きい最小の要素を返す。存在しなければ None を返す。"
        return s.ge(x + 1)

    def ge(s, x):
        "x 以上の最小の要素を返す。存在しなければ None を返す。"
        for a in s.a:
            if a[-1] >= x:  # gt なら >
                return a[bisect_left(a, x)]  # gt なら bisect_right
    
    def __getitem__(s, i):
        "i 番目の要素を返す。"
        if i < 0:
            for a in reversed(s.a):
                i += len(a)
                if i >= 0: return a[i]
        else:
            for a in s.a:
                if i < len(a): return a[i]
                i -= len(a)
        raise IndexError
    
    def pop(s, i=-1):
        "i 番目の要素を削除して返す。"
        if i < 0:
            for b, a in enumerate(reversed(s.a)):
                i += len(a)
                if i >= 0: return s._pop(a, ~b, i)
        else:
            for b, a in enumerate(s.a):
                if i < len(a): return s._pop(a, b, i)
                i -= len(a)
        raise IndexError

    def index(s, x):
        "x 未満の要素数を返す。"
        ans = 0
        for a in s.a:
            if a[-1] >= x:  # index_right なら >
                return ans + bisect_left(a, x)  # index_right なら bisect_right
            ans += len(a)
        return ans

    def index_right(s, x):
        "x 以下の要素数を返す。"
        return s.index(x + 1)

    def __len__(s):
        return s.size

    def __str__(s):
        return "{" + str(list(s))[1:-1] + "}"
